import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = []; page.on('pageerror', error => errors.push(error.message));
const base = process.env.FINGERTIP_BASE || 'https://nmnhut.dev/magic-dust/lessons';
await page.goto(`${base}/fingertips-lesson.html?v=${Date.now()}`, { waitUntil: 'networkidle', timeout: 120000 });
await page.waitForFunction(() => window.fingertipsDeck?.isReady?.());
await page.evaluate(() => { fingertipsDeck.slide(1); for (let i = 0; i < 8; i += 1) fingertipsDeck.nextFragment(); });
await page.waitForTimeout(500); await page.screenshot({ path: '../artifacts-fingertips-slide-process.png' });
await page.evaluate(() => fingertipsDeck.slide(7));
for (let i = 0; i < 5; i += 1) await page.locator('#scanNext').click();
await page.screenshot({ path: '../artifacts-fingertips-slide-scan.png' });
console.log(JSON.stringify({ processHighlights: await page.locator('.process-focus').count(), scanCount: await page.locator('#scanCount').innerText(), errors }, null, 2));
await browser.close();
